/**
 * Returns model options for a given brand name.
 * If brand is unlisted, 'Other', or empty, returns [OTHER_OPTION].
 * Always appends 'Other' so unlisted models for listed brands can be entered.
 */
export function getModelsForBrand(brandName: string): string[] {
  if (!brandName || brandName === OTHER_OPTION) {
    return [OTHER_OPTION];
  }

  const cleanName = brandName.trim().toLowerCase();
  const canonical = BRAND_ALIASES[cleanName] || cleanName;

  const match = CAR_BRANDS_DATA.find(
    (b) => b.name.toLowerCase() === canonical.toLowerCase()
  );

  if (!match) {
    return [OTHER_OPTION];
  }

  return [...match.models, OTHER_OPTION];
}
